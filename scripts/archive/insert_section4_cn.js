const existing = doc.getParagraphs();
const first = existing.length > 0 ? existing[0] : null;
const firstText = first ? first.getText() : null;
let insertIndex = 0;
let setFirst = false;
if (first && (firstText === null || firstText.trim() === "")) {
  setFirst = true;
} else {
  insertIndex = 0;
}

let written = 0;
for (let i = 0; i < paras.length; i++) {
  const [kind, text] = paras[i];
  if (i === 0 && setFirst) {
    const ok1 = first.setText(text);
    if (!ok1) throw new Error("setText failed on first paragraph");
    const style = kind === "b" ? BODY : HEAD;
    const ok2 = first.setStyle(style);
    if (!ok2) throw new Error("setStyle failed on first paragraph");
    written++;
    continue;
  }
  const idx = (setFirst ? 1 : 0) + (setFirst ? (i - 1) : i);
  const p = doc.insertParagraph(idx, text);
  const style = kind === "b" ? BODY : HEAD;
  const ok = p.setStyle(style);
  if (!ok) throw new Error("setStyle failed at paragraph " + i);
  written++;
}

return JSON.stringify({
  totalParagraphs: doc.getParagraphs().length,
  written,
  firstTextNow: doc.getParagraphs()[0].getText(),
});
