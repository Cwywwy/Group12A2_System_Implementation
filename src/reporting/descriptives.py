from __future__ import annotations

from pathlib import Path

import pandas as pd

from src.config import (
    BENEISH_THRESHOLD,
    FINANCE_FEATURES,
    TEXT_FEATURES,
)

TEXT_QUALITY_ORDER = ("ok", "suspicious", "missing")
AUDIT_STATUS_ORDER = ("ok", "missing", "too_small", "mismatched_year")


def _md_table(df: pd.DataFrame) -> str:
    """Minimal dependency-free markdown table (tabulate-free)."""
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "| " + " | ".join("---" for _ in df.columns) + " |"
    body = [
        "| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |"
        for row in df.itertuples(index=False, name=None)
    ]
    return "\n".join([header, sep, *body])


def describe_download_coverage(audit: pd.DataFrame) -> pd.DataFrame:
    """Counts per year and status for the download audit."""
    out = (
        audit.groupby(["fiscal_year", "status"]).size()
        .unstack(fill_value=0)
        .reindex(columns=AUDIT_STATUS_ORDER, fill_value=0)
    )
    out["total"] = out.sum(axis=1)
    out["coverage"] = (out["ok"] / out["total"]).round(4)
    return out


def describe_text_coverage(ft: pd.DataFrame) -> pd.DataFrame:
    """Counts per year of text_quality classes."""
    if "text_quality" not in ft.columns:
        return pd.DataFrame()
    out = (
        ft.groupby(["fiscal_year", "text_quality"]).size()
        .unstack(fill_value=0)
        .reindex(columns=TEXT_QUALITY_ORDER, fill_value=0)
    )
    out["total"] = out.sum(axis=1)
    out["share_ok"] = (out["ok"] / out["total"]).round(4)
    return out


def describe_feature_summary(ft: pd.DataFrame) -> pd.DataFrame:
    """n / mean / std / min / max for every model feature on non-missing rows."""
    cols = [c for c in [*FINANCE_FEATURES, *TEXT_FEATURES] if c in ft.columns]
    rows = []
    for col in cols:
        s = ft[col]
        rows.append(
            {
                "feature": col,
                "n": int(s.notna().sum()),
                "mean": round(float(s.mean(skipna=True)), 6),
                "std": round(float(s.std(skipna=True)), 6),
                "min": round(float(s.min(skipna=True)), 6),
                "max": round(float(s.max(skipna=True)), 6),
            }
        )
    return pd.DataFrame(rows)


def describe_benchmark(ft: pd.DataFrame) -> pd.DataFrame:
    """Beneish M-Score availability and flagged share (M > threshold)."""
    if "m_score" not in ft.columns:
        return pd.DataFrame()
    m = ft["m_score"]
    rows = []
    for year, grp in ft.groupby("fiscal_year"):
        s = grp["m_score"]
        n = int(s.notna().sum())
        rows.append(
            {
                "fiscal_year": year,
                "m_score_n": n,
                "flagged_n": int((s > BENEISH_THRESHOLD).sum()),
                "flagged_share": round(float((s > BENEISH_THRESHOLD).mean()), 4),
            }
        )
    out = pd.DataFrame(rows)
    out["all_n"] = int(m.notna().sum())
    out["all_flagged_n"] = int((m > BENEISH_THRESHOLD).sum())
    return out


def build_descriptives_report(
    ft: pd.DataFrame, audit: pd.DataFrame, out_md: Path
) -> dict:
    """Write a markdown descriptives report; return a small summary dict."""
    lines: list[str] = ["# Descriptives Summary", ""]
    lines.append("Auto-generated by scripts/run_11_descriptives.py.")
    lines.append("")

    if "fiscal_year" in ft.columns and "symbol" in ft.columns:
        by_year = (
            ft.groupby("fiscal_year")
            .agg(firm_years=("symbol", "size"), firms=("symbol", "nunique"))
            .reset_index()
        )
        lines.append("## 1. Sample firm-years")
        lines.append("")
        lines.append(by_year.pipe(_md_table))
        lines.append("")

    if not audit.empty:
        lines.append("## 2. Download coverage (audit)")
        lines.append("")
        lines.append(describe_download_coverage(audit).reset_index().pipe(_md_table))
        lines.append("")

    text_cov = describe_text_coverage(ft)
    if not text_cov.empty:
        lines.append("## 3. Text feature availability (text_quality)")
        lines.append("")
        lines.append(text_cov.reset_index().pipe(_md_table))
        lines.append("")

    feat = describe_feature_summary(ft)
    if not feat.empty:
        lines.append("## 4. Feature summary (non-missing rows)")
        lines.append("")
        lines.append(feat.pipe(_md_table))
        lines.append("")

    bench = describe_benchmark(ft)
    if not bench.empty:
        lines.append("## 5. Beneish M-Score benchmark flags (M > -1.78)")
        lines.append("")
        lines.append(bench.pipe(_md_table))
        lines.append("")

    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text("\n".join(lines), encoding="utf-8")
    return {
        "firm_years": int(ft.shape[0]),
        "firms": int(ft["symbol"].nunique()) if "symbol" in ft.columns else 0,
        "audit_ok": int((audit["status"] == "ok").sum()) if not audit.empty else 0,
        "text_ok": int((ft["text_quality"] == "ok").sum()) if "text_quality" in ft.columns else 0,
    }
